"""Drafts candidate benchmark questions from the ingested corpus.

The failure mode this guards against: a question generated by quoting a
passage retrieves that passage trivially, so every configuration scores near
100% and the benchmark measures nothing. The prompt therefore demands
paraphrase and forbids reusing distinctive wording — and the output is still
only a *draft*, because no prompt makes human review unnecessary.
"""

from __future__ import annotations

import json
import logging
from uuid import UUID

from sqlalchemy.orm import Session

from app.generation.llm import groq_client
from evaluation.config import (
    DRAFT_CHUNK_SAMPLE_SIZE,
    DRAFT_MIN_CHUNK_CHARS,
    DRAFT_QUESTIONS_PER_CHUNK,
    DRAFT_SNIPPET_CHARS,
)
from evaluation.corpus import sample_chunks, section_of
from evaluation.schema import GoldQuestion

logger = logging.getLogger(__name__)

SYSTEM_PROMPT = (
    "You write evaluation questions for a document retrieval benchmark. "
    "Your questions must be answerable from the passage, but must NOT copy its "
    "phrasing.\n"
    "Rules:\n"
    "1. Paraphrase. Do not reuse distinctive nouns, headings, or phrases from "
    "the passage — a question that quotes the passage is trivially retrievable "
    "and makes the benchmark worthless.\n"
    "2. Write the way a user who has NOT read the document would ask.\n"
    "3. Each question must be specific enough to have one correct source "
    "section. Avoid 'what does this document say about X'.\n"
    "4. No yes/no questions.\n"
    "5. Reply with a JSON array of strings and nothing else."
)


def _parse_questions(raw: str) -> list[str]:
    """Tolerate a model that wraps JSON in prose or emits a bare list."""
    try:
        parsed = json.loads(raw)
        if isinstance(parsed, list):
            return [str(item).strip() for item in parsed if str(item).strip()]
    except json.JSONDecodeError:
        logger.debug("Draft response was not valid JSON; falling back to lines")

    questions: list[str] = []
    for line in raw.splitlines():
        cleaned = line.strip().lstrip("-*0123456789. ").strip().strip('",')
        if cleaned.endswith("?"):
            questions.append(cleaned)
    return questions


def draft_questions(session: Session, owner_id: UUID) -> list[GoldQuestion]:
    chunks = sample_chunks(
        session,
        owner_id,
        limit=DRAFT_CHUNK_SAMPLE_SIZE,
        min_chars=DRAFT_MIN_CHUNK_CHARS,
    )
    if not chunks:
        raise RuntimeError(
            "No indexed chunks found for this account. Upload and ingest "
            "documents before drafting questions."
        )

    drafted: list[GoldQuestion] = []
    for chunk, document_title in chunks:
        user_prompt = (
            f"Document: {document_title}\n"
            f"Section: {section_of(chunk, document_title)}\n"
            f"Passage:\n{chunk.text[:DRAFT_SNIPPET_CHARS]}\n\n"
            f"Write {DRAFT_QUESTIONS_PER_CHUNK} questions."
        )
        try:
            raw = groq_client.complete(SYSTEM_PROMPT, user_prompt)
        except Exception:  # noqa: BLE001 - one bad chunk must not end the run
            logger.exception("Drafting failed for chunk %s", chunk.id)
            continue

        for question in _parse_questions(raw)[:DRAFT_QUESTIONS_PER_CHUNK]:
            drafted.append(
                GoldQuestion(
                    question=question,
                    expected_section=section_of(chunk, document_title),
                    document_title=document_title,
                    source_chunk_id=chunk.id,
                )
            )

    logger.info("Drafted %d candidate questions", len(drafted))
    return drafted
